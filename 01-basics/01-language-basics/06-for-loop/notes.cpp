// 📍 demonstration (conditionals inside loops)
#include <bits/stdc++.h>
using namespace std;
int main()
{
    for (int i = 1; i <= 10; i++)
    {
        if (i % 2 == 0)
        {
            cout << i << " is even." << endl;
        }
        else
        {
            cout << i << " is odd." << endl;
        }
    }
    return 0;
};

